import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE)
const fixture = JSON.parse(await readFile(process.env.COMMUNITY_BROWSER_FIXTURE, 'utf8'))
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH })
const base=process.env.COMMUNITY_BASE_URL, out=process.env.COMMUNITY_ARTIFACT_DIR
const checks=[],errors=[]
try {
 for(const [role,identity] of Object.entries(fixture.users)){
  const context=await browser.newContext({viewport:{width:1440,height:1050},timezoneId:'Asia/Shanghai'})
  await context.addInitScript(user=>{if(user){localStorage.setItem('auth_token',user.token);localStorage.setItem('auth_user',JSON.stringify(user.user))}if(!localStorage.getItem('sc-wiki.language'))localStorage.setItem('sc-wiki.language','zh')},identity)
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message))
  await page.goto(`${base}/share/discussions`);await page.getByRole('heading',{name:'AI 学术讨论',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:/^生成答案/}).count(),0)
  const questionUrl=`${base}/share/discussions/${fixture.question_id}`
  await page.goto(questionUrl)
  await page.getByRole('heading',{name:fixture.question_title,exact:true}).waitFor()
  const card=page.getByRole('link',{name:'查看 DeepSeek 的完整回答'})
  await card.waitFor()
  assert.equal(await page.getByText('补充回答',{exact:true}).count(),0)
  assert((await card.boundingBox()).width<=680)
  assert((await card.boundingBox()).height<220)
  await page.screenshot({path:`${out}/${role}-desktop.png`,fullPage:true})
  await card.click()
  await page.getByText('补充回答',{exact:true}).first().waitFor()
  assert.match(page.url(),/\/answers\/\d+$/)
  const detailUrl=page.url()
  await page.reload();await page.getByText('补充回答',{exact:true}).first().waitFor()
  assert.equal(page.url(),detailUrl)
  await page.screenshot({path:`${out}/${role}-detail.png`})
  const reference=page.getByRole('link',{name:/OpenAI #/}).first()
  await reference.click();await page.getByText('OpenAI',{exact:true}).waitFor()
  assert.match(page.url(),/\/answers\/\d+#answer-A\d+/)
  await page.getByRole('link',{name:'返回问题',exact:true}).click()
  await card.waitFor()
  if(role==='superadmin'){
   await page.getByRole('button',{name:'生成答案 (2)',exact:true}).waitFor()
   assert.equal(await page.getByRole('dialog').count(),0)
   await page.getByRole('button',{name:'DeepSeek',exact:true}).click()
   await page.getByRole('button',{name:'OpenAI',exact:true}).click()
   assert.equal(await page.getByRole('button',{name:'生成答案 (0)',exact:true}).isDisabled(),true)
   await page.getByRole('button',{name:'OpenAI',exact:true}).click()
   await page.getByRole('button',{name:'DeepSeek',exact:true}).click()
   const response=page.waitForResponse(r=>r.url().endsWith('/answers/batch')&&r.request().method()==='POST')
   await page.getByRole('button',{name:'生成答案 (2)',exact:true}).click()
   const res=await response;assert.equal(res.status(),202)
   const group=await res.json();assert.deepEqual(group.items.map(item=>item.model_name),['OpenAI','DeepSeek'])
   await page.getByText('等待生成',{exact:true}).last().waitFor()
   await page.screenshot({path:`${out}/model-selector.png`,fullPage:true})
   checks.push('原子批量接口真实提交两模型，顺序OpenAI→DeepSeek，无弹窗')
  } else assert.equal(await page.getByRole('button',{name:/^生成答案/}).count(),0)
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.screenshot({path:`${out}/${role}-mobile.png`})
  await card.click();await page.getByText('补充回答',{exact:true}).first().waitFor()
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.screenshot({path:`${out}/${role}-detail-mobile.png`})
  await page.evaluate(()=>localStorage.setItem('sc-wiki.language','en'));await page.reload()
  await page.getByText('Follow-up answer',{exact:true}).first().waitFor()
  checks.push(`${role}: 680px摘要、独立答案页、刷新、跨答案引用、返回、窄屏与英文通过`)
  await context.close()
 }
 assert.deepEqual(errors,[])
 await writeFile(`${out}/browser.json`,JSON.stringify({checks,errors},null,2))
 console.log(`PASS browser ${checks.length} checks`)
}finally{await browser.close()}

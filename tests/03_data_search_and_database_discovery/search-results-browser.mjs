import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const root=process.env.FRONTEND_URL || 'http://127.0.0.1:18578'
const artifacts=process.env.ARTIFACT_DIR || '/tmp/scwiki178-browser-artifacts'
await fs.mkdir(artifacts,{recursive:true})
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'})
const errors=[],requests=[]
try {
 const context=await browser.newContext({viewport:{width:1400,height:1000}})
 context.on('page',p=>{p.on('pageerror',e=>errors.push(e.message));p.on('request',r=>{if(r.url().includes('/api/'))requests.push({method:r.method(),path:new URL(r.url()).pathname,body:r.postData()})})})
 const page=await context.newPage();await page.goto(root+'/search')
 await page.locator('input').first().fill('LaSc2H24')
 const [results]=await Promise.all([page.waitForEvent('popup'),page.getByRole('link',{name:'搜索',exact:true}).click()])
 await results.getByTestId('search-paper-card').first().waitFor()
 assert.equal(await results.getByTestId('search-paper-card').count(),1)
 assert.equal(await page.locator('input').first().inputValue(),'LaSc2H24')
 assert.equal(await results.getByRole('button',{name:'按论文',exact:true}).getAttribute('aria-pressed'),'true')
 await results.screenshot({path:path.join(artifacts,'papers-desktop.png'),fullPage:true})
 const count=context.pages().length
 await results.getByRole('button',{name:'按材料状态',exact:true}).click()
 await results.getByTestId('search-state-card').nth(7).waitFor()
 assert.equal(context.pages().length,count)
 assert.equal(await results.getByTestId('search-state-card').count(),8)
 assert.equal(await results.getByText('结果表格',{exact:true}).count(),0)
 await results.screenshot({path:path.join(artifacts,'states-desktop.png'),fullPage:true})
 const stateURL=results.url()
 await results.reload();await results.getByTestId('search-state-card').nth(7).waitFor()
 assert.equal(results.url(),stateURL)
 const [paper]=await Promise.all([results.waitForEvent('popup'),results.getByRole('link',{name:'查看来源论文',exact:true}).first().click()])
 await paper.getByText('论文详情',{exact:true}).waitFor()
 assert.equal(await paper.getByText('返回上传列表',{exact:true}).count(),0)
 await paper.getByRole('button',{name:'返回检索结果',exact:true}).click()
 await paper.getByTestId('search-state-card').nth(7).waitFor();assert.equal(paper.url(),stateURL)
 const [structure]=await Promise.all([results.waitForEvent('popup'),results.getByRole('link',{name:'查看结构与下载',exact:true}).first().click()])
 await structure.getByRole('button',{name:'下载 CIF',exact:true}).waitFor()
 assert.equal(await structure.getByRole('link',{name:'查看来源论文',exact:true}).getAttribute('target'),'_blank')
 await results.getByRole('button',{name:'按论文',exact:true}).click();await results.getByTestId('search-paper-card').waitFor()
 await results.goBack();await results.getByTestId('search-state-card').nth(7).waitFor()
 await results.setViewportSize({width:390,height:844})
 await results.screenshot({path:path.join(artifacts,'states-mobile.png'),fullPage:true})
 assert.ok(await results.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile horizontal overflow')
 await results.goto(root+'/search?elements=La,Sc&mode=elements_exact_search')
 await results.getByTestId('search-paper-card').waitFor();await results.getByRole('button',{name:'按材料状态',exact:true}).click()
 await results.getByText('没有匹配记录',{exact:true}).waitFor()
 await results.goto(root+'/search?elements=Fe&mode=elements_exact_search&view=states&state_page=2')
 await results.getByTestId('search-state-card').nth(19).waitFor()
 assert.equal(await results.getByTestId('search-state-card').count(),20)
 const pagedURL=results.url()
 const [pagedPaper]=await Promise.all([results.waitForEvent('popup'),results.getByRole('link',{name:'查看来源论文',exact:true}).first().click()])
 await pagedPaper.getByRole('button',{name:'返回检索结果',exact:true}).click()
 await pagedPaper.getByTestId('search-state-card').nth(19).waitFor();assert.equal(pagedPaper.url(),pagedURL)
 await results.getByRole('button',{name:'按论文',exact:true}).focus();await results.keyboard.press('Enter')
 await results.getByTestId('search-paper-card').waitFor()
 // 非法来路必须回退站内检索，不能离开同源。
 await paper.goto(root+'/papers/271?return='+encodeURIComponent('//evil.invalid'))
 await paper.getByRole('button',{name:'返回检索结果',exact:true}).click()
 assert.ok(paper.url().startsWith(root+'/search'))
 assert.deepEqual(errors,[])
 await fs.writeFile(path.join(artifacts,'browser.json'),JSON.stringify({passed:true,cases:['new-result-tab','default-paper','same-page-eight-states','no-tc-table','refresh','paper-popup-return','structure-popup','back','mobile','independent-source-paper','unsafe-return','page-two-return','keyboard-toggle'],errors,requests},null,2))
 console.log('passed browser cases; artifacts:',artifacts)
} finally {await browser.close()}
